static const CoralGlyph *coral_glyph_lookup(char code)
{
	size_t i;

	if (code >= 'a' && code <= 'z')
		code -= 'a' - 'A';

	for (i = 0; i < sizeof(coral_glyphs) / sizeof(coral_glyphs[0]); i++) {
		if (coral_glyphs[i].code == code)
			return &coral_glyphs[i];
	}

	return &coral_glyphs[0]; /* fall back to a space */
}

int coral_text_width(const char *text, int scale)
{
	int length = 0;

	if (text == NULL || *text == '\0' || scale <= 0)
		return 0;

	while (*text++ != '\0')
		length++;

	return length * (GLYPH_WIDTH + GLYPH_SPACING) * scale - GLYPH_SPACING * scale;
}

int coral_text_height(int scale)
{
	if (scale <= 0)
		return 0;

	return GLYPH_HEIGHT * scale;
}

void coral_text_draw(CoralRenderer *renderer, float x, float y, int scale,
                     const char *text, u64 color)
{
	int cursor = (int)x;
	int base_y = (int)y;

	if (text == NULL || scale <= 0)
		return;

	while (*text != '\0') {
		const CoralGlyph *glyph = coral_glyph_lookup(*text);
		int row;

		for (row = 0; row < GLYPH_HEIGHT; row++) {
			unsigned char bits = glyph->rows[row];
			int column;

			for (column = 0; column < GLYPH_WIDTH; column++) {
				if ((bits >> (GLYPH_WIDTH - 1 - column)) & 1) {
					coral_renderer_fill_rect(renderer,
					                         (float)(cursor + column * scale),
					                         (float)(base_y + row * scale),
					                         (float)scale, (float)scale,
					                         color);
				}
			}
		}

		cursor += (GLYPH_WIDTH + GLYPH_SPACING) * scale;
		text++;
	}
}
